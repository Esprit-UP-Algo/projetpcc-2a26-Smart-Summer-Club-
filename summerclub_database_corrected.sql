-- Trigger for ACTIVITIES (matches your original trigger name)
CREATE OR REPLACE TRIGGER SUMMERCLUB.ACTIVITY_ID_TRIGGER
    BEFORE INSERT ON SUMMERCLUB.ACTIVITIES
    FOR EACH ROW
BEGIN
    IF :NEW.ID_A IS NULL THEN
        :NEW.ID_A := SUMMERCLUB.ACTIVITY_ID_SEQ.NEXTVAL;
    END IF;
END;
/

-- Enable the trigger explicitly
ALTER TRIGGER SUMMERCLUB.ACTIVITY_ID_TRIGGER ENABLE;

