-- Drop foreign key constraints first to avoid ORA-02449 errors
BEGIN
    FOR c IN (SELECT constraint_name, table_name 
              FROM user_constraints 
              WHERE constraint_type = 'R' 
              AND owner = 'SUMMERCLUB') LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE SUMMERCLUB.' || c.table_name || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION
            WHEN OTHERS THEN NULL; -- Ignore if constraint doesn't exist
        END;
    END LOOP;
END;
/

-- Drop tables with CASCADE CONSTRAINTS to handle any remaining references
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE owner = 'SUMMERCLUB') LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE SUMMERCLUB.' || t.table_name || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN NULL; -- Ignore if table doesn't exist
        END;
    END LOOP;
END;
/

-- Drop sequences
BEGIN
    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_owner = 'SUMMERCLUB') LOOP
