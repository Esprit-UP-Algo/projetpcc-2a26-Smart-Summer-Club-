-- Create ACTIVITIES table (referenced by EMPLOYEES and PARTICIPATE)
CREATE TABLE SUMMERCLUB.ACTIVITIES (
    ID_A NUMBER,
    ACTIVITY_TYPE VARCHAR2(50 BYTE),
    EVENT_DATE DATE,
    EVENT_TIME TIMESTAMP(6),
    RESPONSIBLE VARCHAR2(100 BYTE),
    AGE_REQUIREMENT NUMBER(3,0),
    STATUS VARCHAR2(20 BYTE) DEFAULT 'Scheduled',
    DESCRIPTION CLOB,
    CAPACITY NUMBER(5,0),
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ACTIVITY PRIMARY KEY (ID_A)
);

-- Create MEMBERS table (referenced by PARTICIPATE and TRANSACTIONS)
CREATE TABLE SUMMERCLUB.MEMBERS (
    CIN VARCHAR2(50 BYTE),
    FIRST_NAME VARCHAR2(100 BYTE) NOT NULL,
    LAST_NAME VARCHAR2(100 BYTE) NOT NULL,
    GENDER VARCHAR2(10 BYTE),
    AGE NUMBER,
    EMAIL VARCHAR2(255 BYTE),
    PHONE VARCHAR2(20 BYTE),
    SUBSCRIPTION_PLAN VARCHAR2(50 BYTE),
    JOIN_DATE DATE,
    PHOTO BLOB,
    CREATED_DATE DATE DEFAULT SYSDATE,
    UPDATED_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT PK_MEMBERS PRIMARY KEY (CIN),
    CONSTRAINT CHK_MEMBER_EMAIL CHECK (REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'))
);

-- Create EQUIPEMENTS table (referenced by MANAGE)
CREATE TABLE SUMMERCLUB.EQUIPEMENTS (
    ID_EQ NUMBER,
    EQUIP_CODE VARCHAR2(50 BYTE) NOT NULL,
    NAME VARCHAR2(100 BYTE) NOT NULL,
    CATEGORY VARCHAR2(50 BYTE),
    TOTAL_QUANTITY NUMBER(5,0),
    AVAILABLE NUMBER(5,0),
    IN_USE NUMBER(5,0),
    UNDER_MAINTENANCE NUMBER(5,0),
    STATUS VARCHAR2(20 BYTE) DEFAULT 'Available',
    BRAND VARCHAR2(50 BYTE),
    MODEL VARCHAR2(50 BYTE),
    PURCHASE_DATE DATE,
    PURCHASE_PRICE NUMBER(10,2),
    LOCATION VARCHAR2(100 BYTE),
    NOTES CLOB,
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_EQUIPEMENTS PRIMARY KEY (ID_EQ),
    CONSTRAINT UK_EQUIP_CODE UNIQUE (EQUIP_CODE)
);

-- Create EMPLOYEES table (references ACTIVITIES, referenced by MANAGE and TRANSACTIONS)
CREATE TABLE SUMMERCLUB.EMPLOYEES (
    CIN VARCHAR2(50 BYTE),
    FIRST_NAME VARCHAR2(100 BYTE) NOT NULL,
    LAST_NAME VARCHAR2(100 BYTE) NOT NULL,
    POSITION VARCHAR2(50 BYTE),
    DEPARTMENT VARCHAR2(50 BYTE),
    HIRE_DATE DATE,
    STATUS VARCHAR2(20 BYTE) DEFAULT 'Active',
    AGE NUMBER(3,0),
    GENDER VARCHAR2(10 BYTE),
    EMAIL VARCHAR2(255 BYTE),
    PHONE VARCHAR2(20 BYTE),
    SALARY NUMBER(10,2),
    PASSWORD VARCHAR2(255 BYTE),
    PHOTO BLOB,
    ID_A NUMBER,
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_EMPLOYEES PRIMARY KEY (CIN),
    CONSTRAINT CHK_EMP_EMAIL CHECK (REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
    CONSTRAINT FK_EMPLOYEE_ACTIVITY FOREIGN KEY (ID_A) REFERENCES SUMMERCLUB.ACTIVITIES(ID_A) ON DELETE SET NULL
);

-- Create PARTICIPATE table (junction table - references MEMBERS and ACTIVITIES)
CREATE TABLE SUMMERCLUB.PARTICIPATE (
    CIN VARCHAR2(50 BYTE) NOT NULL,
    ID_A NUMBER NOT NULL,
    CONSTRAINT PK_PARTICIPATE PRIMARY KEY (CIN, ID_A),
    CONSTRAINT FK_PARTICIPATE_MEMBER FOREIGN KEY (CIN) REFERENCES SUMMERCLUB.MEMBERS(CIN) ON DELETE CASCADE,
    CONSTRAINT FK_PARTICIPATE_ACTIVITY FOREIGN KEY (ID_A) REFERENCES SUMMERCLUB.ACTIVITIES(ID_A) ON DELETE CASCADE
);

-- Create MANAGE table (junction table - references EMPLOYEES and EQUIPEMENTS)
CREATE TABLE SUMMERCLUB.MANAGE (
    CIN VARCHAR2(50 BYTE) NOT NULL,
    ID_EQ NUMBER NOT NULL,
    CONSTRAINT PK_MANAGE PRIMARY KEY (CIN, ID_EQ),
    CONSTRAINT FK_MANAGE_EMPLOYEE FOREIGN KEY (CIN) REFERENCES SUMMERCLUB.EMPLOYEES(CIN) ON DELETE CASCADE,
    CONSTRAINT FK_MANAGE_EQUIPMENT FOREIGN KEY (ID_EQ) REFERENCES SUMMERCLUB.EQUIPEMENTS(ID_EQ) ON DELETE CASCADE
);

-- Create TRANSACTIONS table (references EMPLOYEES)
CREATE TABLE SUMMERCLUB.TRANSACTIONS (
    ID_TR NUMBER,
    TRANSACTION_ID VARCHAR2(100 BYTE) NOT NULL,
    PAYMENT_DATE DATE,
    DESCRIPTION VARCHAR2(500 BYTE),
    PAYMENT_TYPE VARCHAR2(50 BYTE),
    AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(50 BYTE),
    STATUS VARCHAR2(20 BYTE) DEFAULT 'Pending',
    MEMBER_ID VARCHAR2(50 BYTE) NOT NULL,
    CIN VARCHAR2(50 BYTE),
    CREATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID_TR),
    CONSTRAINT UK_TRANSACTION_ID UNIQUE (TRANSACTION_ID),
    CONSTRAINT FK_TRANSACTIONS_EMPLOYEE FOREIGN KEY (CIN) REFERENCES SUMMERCLUB.EMPLOYEES(CIN) ON DELETE SET NULL
);

